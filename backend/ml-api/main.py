def generate_jerry_response(text: str, ctx: ResponseContext, language: str) -> str | None:
    """Use Gemini to generate a natural-language response from real task data."""
    if not ctx:
        return None
    if not client:
        return _template_fallback(ctx, language)

    intent = ctx.intent or ""
    tasks = ctx.matched_tasks or []
    created = ctx.created_task or None
    meeting = ctx.meeting or None
    last_created = ctx.last_created_task or None
    label = ctx.label or ""

    # Build a concise data summary for Gemini (no sensitive fields)
    def _summarize_task(t: dict) -> dict:
        due = t.get("due_date") or t.get("due")
        if due and "T" in str(due):
            try:
                dt = datetime.fromisoformat(str(due).replace("Z", "+00:00").split("+")[0])
                time_part = dt.strftime("%I:%M %p").lstrip("0")
                date_part = dt.strftime("%b %d")
                due_str = f"{date_part} at {time_part}" if dt.hour or dt.minute else date_part
            except Exception:
                due_str = str(due)[:16]
        else:
            due_str = str(due) if due else None
        return {
            "title": t.get("title", ""),
            "due": due_str,
            "priority": t.get("priority", "medium"),
            "status": t.get("status", "todo"),
        }

    tasks_summary = [_summarize_task(t) for t in tasks[:10]]
    recent_summary = [_summarize_task(t) for t in (last_created or [])[:3]] if isinstance(last_created, list) else ([_summarize_task(last_created)] if last_created else [])

    prompt = (
        'User asked: ' + text + chr(10)
        + 'Intent: ' + intent + chr(10)
        + 'Query type: ' + (ctx.query or 'N/A') + chr(10)
    )
    if tasks_summary:
        prompt += f"Task data ({len(tasks)} tasks, label: {label}):\n"
        for t in tasks_summary:
            prompt += f"  - {t['title']} | due: {t['due'] or 'none'} | priority: {t['priority']} | status: {t['status']}\n"
    if recent_summary:
        prompt += f"\nLast created task: {recent_summary[0]['title']}\n"
    if created:
        prompt += f"\nTask just created: {created.get('title', '')} | due: {created.get('due_date', 'none')}\n"
    if meeting:
        prompt += f"\nLatest meeting: {meeting.get('title', '')}\n"
    if ctx.duplicate:
        prompt += "\nNote: A task with this title already exists. Inform the user.\n"
    if ctx.not_found:
        prompt += "\nNote: Could not find a matching task. Ask the user to be more specific.\n"
    if ctx.error:
        prompt += "\nNote: The operation failed. Apologize and ask them to try again.\n"

    lang_instruction = "Respond in Hindi/Hinglish. Do not translate word-for-word -- be natural." if language == "hi" else "Respond in English."
    prompt += (
        "\n\nYou are Jerry, a friendly productivity assistant inside FlowTask.\n"
        + lang_instruction + "\n\n"
        + "RULES:\n"
        + "- Be concise (1-3 sentences max).\n"
        + "- Use the REAL data above. Do NOT invent or hallucinate any task information.\n"
        + "- If no tasks: say so naturally.\n"
        + "- For task creation confirmations: confirm the title and due date if available.\n"
        + "- For queries: summarize what's relevant, highlight urgent/overdue items.\n"
        + "- For ambiguous matches: list the options and ask which one.\n"
        + "- Sound natural and helpful, not robotic.\n"
        + "- Never mention internal details like IDs, database, or backend.\n"
        + "- If the user made a follow-up (e.g. 'make it 5 PM'), acknowledge what was changed.\n"
    )

    try:
        response = client.models.generate_content(
            model=GEMINI_MODEL,
            contents=prompt,
            config=genai.types.GenerateContentConfig(
                system_instruction="You are Jerry, a concise productivity assistant.",
                temperature=0.3,
                max_output_tokens=200,
            ),
        )
        result = (response.text or "").strip()
        if result and len(result) > 5:
            return result
    except Exception as e:
        error_str = str(e).lower()
        is_quota = any(k in error_str for k in ("429", "resource_exhausted", "rate", "quota", "too many"))
        if is_quota:
            print(f"[Jerry] Response generation: Gemini quota exhausted (429)")
        else:
            print(f"[Jerry] Response generation failed: {e}")

    # Fallback to template-based response
    return _template_fallback(ctx, language)


def _template_fallback(ctx: ResponseContext, language: str) -> str:
    """Deterministic, robust fallback when Gemini is unavailable."""
    intent = ctx.intent or ""
    tasks = ctx.matched_tasks or []
    label = ctx.label or ""
    created = ctx.created_task or None

    def _task_list_str(task_list: list[dict], max_items: int = 3) -> str:
        parts = []
        for t in task_list[:max_items]:
            title = t.get("title", "")
            due = t.get("due_date") or t.get("due")
            if due and "T" in str(due):
                try:
                    dt = datetime.fromisoformat(str(due).replace("Z", "+00:00").split("+")[0])
                    time_part = dt.strftime("%I:%M %p").lstrip("0")
                    date_part = dt.strftime("%b %d")
                    due_str = f" at {time_part}" if dt.hour or dt.minute else ""
                    parts.append(f"'{title}' ({date_part}{due_str})")
                except Exception:
                    parts.append(f"'{title}'")
            else:
                parts.append(f"'{title}'")
        more = f" and {len(task_list) - max_items} more" if len(task_list) > max_items else ""
        return ", ".join(parts) + more

    # 1. Error state handling across all intents
    if ctx.error:
        if intent == "task_create":
            return "Task create karne mein dikkat aayi. Kripya dobara koshish karein." if language == "hi" else "I could not create the task due to an error. Please try again."
        if intent == "task_query":
            return "Tasks load karne mein dikkat aayi. Kripya dobara koshish karein." if language == "hi" else "I could not retrieve your tasks right now. Please try again."
        if intent == "task_complete":
            return "Task complete karne mein dikkat aayi. Kripya dobara koshish karein." if language == "hi" else "Could not complete the task. Please try again."
        if intent == "task_delete":
            return "Task delete karne mein dikkat aayi. Kripya dobara koshish karein." if language == "hi" else "Could not delete the task. Please try again."
        if intent == "task_update":
            return "Task update karne mein dikkat aayi. Kripya dobara koshish karein." if language == "hi" else "Could not update the task. Please try again."
        return "Kuch gadbad ho gayi. Kripya dobara koshish karein." if language == "hi" else "An error occurred while processing your request. Please try again."

    # 2. Task create
    if intent == "task_create":
        if ctx.duplicate:
            return "Yeh task pehle se maujood hai." if language == "hi" else "A task with that title already exists."
        raw_title = (created.get("title") or "").strip() if created else ""
        if raw_title:
            formatted_title = raw_title[:1].upper() + raw_title[1:]
            return f"Done! Maine '{formatted_title}' aapke tasks mein add kar diya hai." if language == "hi" else f"Done! I've added '{formatted_title}' to your tasks."
        return "Done! Maine task aapke tasks mein add kar diya hai." if language == "hi" else "Done! I've added your task."

    # 3. Task query
    if intent == "task_query":
        query_type = ctx.query or ""
        count = len(tasks)
        if count > 0:
            list_str = _task_list_str(tasks)
            task_noun = "task" if count == 1 else "tasks"
            if language == "hi":
                if query_type == "today":
                    return f"Aapke paas aaj ke {count} task{'s' if count > 1 else ''} hain: {list_str}."
                if query_type == "tomorrow":
                    return f"Aapke paas kal ke {count} task{'s' if count > 1 else ''} hain: {list_str}."
                if query_type == "overdue":
                    return f"Aapke paas {count} overdue task{'s' if count > 1 else ''} hain: {list_str}."
                if query_type == "pending":
                    return f"Aapke paas {count} pending task{'s' if count > 1 else ''} hain: {list_str}."
                lbl = label or "open"
                return f"Aapke paas {count} {lbl} task{'s' if count > 1 else ''} hain: {list_str}."
            else:
                if query_type == "today":
                    return f"You have {count} {task_noun} due today: {list_str}."
                if query_type == "tomorrow":
                    return f"You have {count} {task_noun} due tomorrow: {list_str}."
                if query_type == "overdue":
                    return f"You have {count} overdue {task_noun}: {list_str}."
                if query_type == "pending":
                    return f"You have {count} pending {task_noun}: {list_str}."
                lbl = label or "matching"
                return f"You have {count} {lbl} {task_noun}: {list_str}."
        else:
            if language == "hi":
                if query_type == "today":
                    return "Aapke paas aaj ke liye koi task nahi hai."
                if query_type == "tomorrow":
                    return "Aapke paas kal ke liye koi task nahi hai."
                if query_type == "overdue":
                    return "Aapka koi bhi task overdue nahi hai."
                if query_type == "pending":
                    return "Aapka koi bhi task pending nahi hai."
                lbl = label or "matching"
                return f"Aapke paas koi {lbl} task nahi hai."
            else:
                if query_type == "today":
                    return "You have no tasks due today."
                if query_type == "tomorrow":
                    return "You have no tasks due tomorrow."
                if query_type == "overdue":
                    return "You have no overdue tasks."
                if query_type == "pending":
                    return "You have no pending tasks."
                lbl = label or "matching"
                return f"You have no {lbl} tasks."

    # 4. Task complete
    if intent == "task_complete":
        if ctx.not_found:
            return "Mujhe complete karne ke liye koi task nahi mila." if language == "hi" else "I couldn't find that task to mark as complete."
        t_name = (created.get("title") or "task").strip() if created else "task"
        return f"Done! Maine '{t_name}' ko complete mark kar diya hai." if language == "hi" else f"Done! I've marked '{t_name}' as complete."

    # 5. Task delete
    if intent == "task_delete":
        if ctx.not_found:
            return "Mujhe delete karne ke liye koi task nahi mila." if language == "hi" else "I couldn't find that task to delete."
        t_name = (created.get("title") or "task").strip() if created else "task"
        return f"Done! Maine '{t_name}' delete kar diya hai." if language == "hi" else f"Done! I've deleted '{t_name}'."

    # 6. Task update
    if intent == "task_update":
        if ctx.not_found:
            return "Mujhe update karne ke liye koi task nahi mila." if language == "hi" else "I couldn't find that task to update."
        t_name = (created.get("title") or "task").strip() if created else "task"
        return f"Done! Maine '{t_name}' update kar diya hai." if language == "hi" else f"Done! I've updated '{t_name}'."

    # 7. Meeting queries
    if intent in ("meeting_query", "meeting_action_item_query"):
        m = ctx.meeting
        if m:
            m_title = m.get("title") or "Meeting"
            m_sum = m.get("summary") or ""
            return f"Meeting '{m_title}': {m_sum}" if m_sum else f"Found meeting '{m_title}'."
        return "Mujhe koi meeting nahi mili." if language == "hi" else "No meetings found."

    return jerry_reply(intent, language)


def classify_task_intent(text: str) -> tuple[str | None, str | None]:
    lowered = " ".join((text or "").lower().split())
    if not lowered:
        return None, None

    # --- Pre-compute flags ---
    has_hedging = bool(HEDGING_PATTERN.search(lowered))
    has_create_verb = bool(CREATE_VERB_PATTERN.search(lowered))

    # --- 1. Greetings: conversational openers, NOT task queries ---
    if GREETING_PATTERN.search(lowered) and len(lowered.split()) <= 8:
        if not has_create_verb:
            return "greeting", None

    # --- 2. Thanks / small talk ---
    if re.search(r"\b(thanks?|thank you|shukriya|dhanyavad|great|awesome|nice|cool|ok|okay|alright)\b", lowered):
        return "conversation", None

    # --- 3. FlowTask help ---
    if re.search(
        r"\b(what can you do|help|how .*work|kya kar sakte|kya kar sakta|what do you do|tum kya karte|"
        r"tell me about flowtask|tell me about this app|what is flowtask|what can flowtask|"
        r"how does flowtask|flowtask kya hai|flowtask kaise kaam)\b",
        lowered,
    ):
        return "flowtask_help", None

    # --- 4. Meeting queries ---
    if re.search(r"\b(summarize|summary|action items?|participants?|agree\w*|meeting|minutes|deadlines? .* meeting)\b", lowered):
        return ("meeting_action_item_query" if re.search(r"action items?|assigned|deadline|agree", lowered) else "meeting_query"), None

    # --- 5. Task mutations (English + Hindi patterns) ---
    if re.search(r"\b(delete|remove|cancel|hatao|hat[aā] do|delete karo|hata de)\b", lowered):
        return "task_delete", None
    if re.search(r"\b(mark|complete|finish|done|pura)\b.*\b(complete|done|task|assignment|kar do|karo|kardia|kar diya)\b", lowered):
        return "task_complete", None
    if re.search(r"\b(complete|done|pura)\b.*\b(kar do|karo)\b", lowered):
        return "task_complete", None
    if re.search(r"\b(move|change|rename|make|shift|update|modify|badal|badal do)\b.*\b(task|assignment|priority|due|friday|monday|high|low|deadline|date)\b", lowered):
        return "task_update", None
    if re.search(r"\b(deadline|date|priority)\b.*\b(badal do|change|update)\b", lowered):
        return "task_update", None

    # --- 6. Task queries ---
    # Only classify as task_query if the sentence is clearly a QUESTION about tasks,
    # NOT an action statement the user wants to perform.
    #
    # KEY RULE: A Hindi sentence like "Mujhe kal DSA padhna hai" is an ACTION,
    # not a question. It must NOT become task_query just because "kal" is present.
    #
    # task_query requires EITHER:
    #   a) An explicit question pattern ("kya tasks hain?", "what do I have?")
    #   b) A query-only keyword WITHOUT any action verb

    # Check if this is a genuine question about tasks (Hindi)
    is_hindi_task_question = bool(HINDI_TASK_QUERY_PATTERN.search(lowered))

    # Check if the sentence contains an action verb (user wants to DO something)
    has_action_verb = bool(re.search(r"\b(" + HINDI_ACTION_VERBS + r")\b", lowered))

    # English task queries: question words + task-related terms
    is_question = lowered.endswith("?") or bool(re.search(
        r"^(what|do|show|list|display|tell|how|which|any|have)\b", lowered,
    ))
    has_task_keyword = bool(re.search(
        r"\b(tasks?|to-?do|assignments?|deadlines?|meetings?|schedule|overdue|pending|upcoming|today|tomorrow|this week|completed|done|urgent|high priority|assigned|focus)\b",
        lowered,
    ))
    is_english_task_query = is_question and has_task_keyword

    # Hindi task queries: explicit question patterns about tasks
    is_hindi_explicit_query = bool(re.search(
        r"\b(kya tasks?|kitne tasks?|tasks? hain|tasks? dikhao|tasks? batao|"
        r"tasks? kaunse|pending tasks?|overdue tasks?|aaj ke tasks?|kal ke tasks?|"
        r"mere tasks?|meri tasks?|kya hai.*task|kitna baaki|kya baaki|"
        r"task overdue|task hai|task kaun|task kya|koi task|kaunsa task|"
        r"kya tasks?|focus on|aaj kya|kal kya)\b",
        lowered,
    ))

    # Determine if this is a task query
    # Rule: If the sentence has an action verb (user wants to DO something), it's NOT a query
    if not has_action_verb:
        # No action verb — check for query patterns
        if is_english_task_query or is_hindi_explicit_query or is_hindi_task_question:
            # Further restrict: only if the sentence is asking, not stating
            if lowered.endswith("?") or is_hindi_explicit_query or is_english_task_query:
                if re.search(r"\b(overdue|late|past due|pichhla)\b", lowered):
                    return "task_query", "overdue"
                if re.search(r"\b(today|aaj)\b", lowered):
                    return "task_query", "today"
                if re.search(r"\b(tomorrow|kal)\b", lowered):
                    return "task_query", "tomorrow"
                if re.search(r"\b(this week|week|upcoming|coming up|agle)\b", lowered):
                    return "task_query", "this_week" if "week" in lowered else "upcoming"
                if re.search(r"\b(urgent|high priority|turant|jaldi)\b", lowered):
                    return "task_query", "urgent"
                if re.search(r"\b(completed|complete|done|finished|ho gaya|ho gya|pura hua)\b", lowered):
                    return "task_query", "completed"
                if re.search(r"\b(assigned to|assigned|mera naam|mere naam)\b", lowered):
                    return "task_query", "assigned"
                if re.search(r"\b(pending|open|unfinished|uncompleted|left to do|bache hue|baaki)\b", lowered):
                    return "task_query", "pending"

    # --- 7. Task assignment ---
    if re.search(r"\b(assign|share|send|bhej|bhej do|forward)\b.*\b(to|ko|se)\b", lowered):
        return "task_assign", None
    if re.search(r"\b(assign|share|send|bhej|bhej do|forward)\b", lowered) and re.search(r"\b(task|report|assignment|project|file|document)\b", lowered):
        return "task_assign", None
    if re.search(r"\b\w+\s+ko\s+(assign|bhej|bhej do)\b", lowered):
        return "task_assign", None

    # --- 8. Hindi task mutation patterns (karo / kar do = do it) ---
    # This MUST come before generic task_create to prevent "X kar do" from being
    # classified as task_create when it's actually a mutation (e.g. "deadline kar do")
    if re.search(r"\b\w+\s+(kar do|karo|kara do|kardia)\b", lowered):
        if re.search(r"\b(delete|remove|hata)\b", lowered):
            return "task_delete", None
        if re.search(r"\b(complete|done|pura|finish)\b", lowered):
            return "task_complete", None
        if re.search(r"\b(change|badal|move|update|modify|rename|deadline|date|priority)\b", lowered):
            return "task_update", None
        if re.search(r"\b\w+\s+(kar do|karo)\b", lowered):
            return "task_update", None

    # --- 9. Hedging / casual statements should NOT create tasks ---
    # "I need to study", "Maybe I should...", "I was thinking about..."
    # These are personal thoughts, NOT task creation requests.
    # But only apply if there's no explicit create verb AND no task-query context.
    if has_hedging and not has_create_verb:
        # If it's very short / generic (e.g. "maybe something"), return unclear
        if len(lowered.split()) <= 3:
            return "unclear", None
        return "conversation", None

    # --- 10. Task creation (verb detected) ---
    if has_create_verb:
        return "task_create", None

    # --- 11. Check for conversational phrases that should NOT become tasks ---
    if re.search(r"\b(kaise ho|kya haal|kaisa hai|theek ho|badhiya|how are you|whats up|kya scene|chal rha|kya kar rahe)\b", lowered):
        return "conversation", None

    # --- 11. General knowledge / out-of-scope ---
    if re.search(r"\b(tell me a joke|write .* poem|capital of|meaning of|definition of|weather|latest news|cricket score|football score|translate|convert|calculate|how much|how many|what is|what are|who is|who was|when was|where is|where was|why do|why does|explain|define|describe)\b", lowered):
        return "out_of_scope", None

    # --- 12. Conversational questions (no task verbs) ---
    if re.search(r"^(what\s+(is|are|was|were)\b|how\s+(do|does|did|can|could|should|to)\b|can\s+(you|i|we)\b|should\s+(i|we)\b)", lowered):
        if not has_create_verb:
            return "conversation", None

    # --- 13. Questions ending with ? without task verbs ---
    if lowered.endswith("?") and not has_create_verb:
        if not re.search(r"\b(today|tomorrow|overdue|pending|upcoming|tasks?|deadline|schedule|calendar|meetings?)\b", lowered):
            return "conversation", None

    # Genuinely ambiguous -- let the Gemini classification step in parse_task() decide
    return None, None

def extract_key_notes_from_transcript(transcript: str) -> list[KeyNote]:
    important_pattern = re.compile(
        r"\b(decided|decision|blocked|blocker|risk|issue|important|deadline|launch|release|approved|problem|concern|priority)\b",
        re.IGNORECASE,
    )
    notes = []
    seen = set()
    statements = split_transcript_statements(transcript)
    for statement in statements:
        speaker, content = split_speaker_statement(statement)
        point = content if speaker else statement
        if not important_pattern.search(point):
            continue
        cleaned = point.strip(" -\t")
        if not cleaned or cleaned.lower() in seen:
            continue
        seen.add(cleaned.lower())
        category = "information"
        lowered = cleaned.lower()
        if "decided" in lowered or "decision" in lowered or "approved" in lowered:
            category = "decision"
        elif "blocked" in lowered or "blocker" in lowered or "risk" in lowered or "issue" in lowered or "concern" in lowered:
            category = "blocker"
        notes.append(KeyNote(point=cleaned[:240], category=category))
        if len(notes) >= 5:
            break

    if notes:
        return notes

    for statement in statements[:5]:
        _, content = split_speaker_statement(statement)
        point = content.strip(" -\t")
        if point:
            notes.append(KeyNote(point=point[:240], category="information"))
    return notes

def request_payload_and_keys(request: AnalyzeMeetingRequest) -> tuple[dict, list[str]]:
    payload = request.model_dump(exclude_none=True)
    extra = getattr(request, "model_extra", None)
    if extra:
        payload.update(extra)
    received_keys = sorted(str(key) for key in getattr(request, "model_fields_set", set()))
    return payload, received_keys

def transcript_from_payload(payload: dict) -> str:
    for field_name in ("transcript", "text", "meeting_text", "meetingText", "content"):
        value = payload.get(field_name)
        if isinstance(value, str) and value.strip():
            return value.strip()
    return ""

def log_final_meeting_response(response: AnalyzeMeetingResponse) -> None:
    print(f"Meeting analysis complete: {len(response.key_notes)} key notes, {len(response.action_items)} action items.")

def fallback_meeting_response(transcript: str) -> AnalyzeMeetingResponse:
    text = " ".join((transcript or "").split())
    if not text:
        return AnalyzeMeetingResponse(
            summary="No meeting transcript content was available to analyze.",
            key_notes=[],
            action_items=[],
        )

    sentences = split_transcript_statements(transcript)
    summary_parts = sentences[:3] or [text[:350]]
    summary = " ".join(summary_parts)
    if len(summary) > 700:
        summary = summary[:697].rstrip() + "..."

    action_items = extract_action_items_from_transcript(transcript)

    key_notes = extract_key_notes_from_transcript(transcript)

    # Extract participants from transcript speaker labels
    participants = []
    seen = set()
    for line in (transcript or "").splitlines():
        speaker, _ = split_speaker_statement(line.strip())
        if speaker and speaker.lower() not in seen:
            seen.add(speaker.lower())
            participants.append(speaker)

    return AnalyzeMeetingResponse(
        summary=summary or "Meeting transcript received, but a detailed AI summary could not be generated.",
        key_notes=key_notes,
        action_items=action_items,
        participants=participants,
    )

def normalize_meeting_analysis(data: dict, transcript: str) -> AnalyzeMeetingResponse:
    if not isinstance(data, dict):
        return fallback_meeting_response(transcript)

    fallback = fallback_meeting_response(transcript)

    summary = data.get("summary") or data.get("meeting_summary") or data.get("overview")
    if isinstance(summary, list):
        summary = " ".join(str(item).strip() for item in summary if str(item).strip())
    elif summary is not None:
        summary = str(summary).strip()
    if not summary:
        summary = fallback.summary

    valid_categories = {"decision", "discussion", "blocker", "information"}
    raw_notes = data.get("key_notes") or data.get("keyNotes") or data.get("notes") or []
    if isinstance(raw_notes, str):
        raw_notes = [raw_notes]

    key_notes = []
    if isinstance(raw_notes, list):
        for note in raw_notes:
            if isinstance(note, dict):
                point = note.get("point") or note.get("text") or note.get("note") or note.get("summary")
                category = str(note.get("category") or "information").lower()
            else:
                point = note
                category = "information"

            point = str(point or "").strip()
            if not point:
                continue
            if category not in valid_categories:
                category = "information"
            key_notes.append(KeyNote(point=point, category=category))

    valid_priorities = {"high", "medium", "low"}
    raw_actions = data.get("action_items") or data.get("actionItems") or data.get("actions") or data.get("tasks") or []
    if isinstance(raw_actions, str):
        raw_actions = [raw_actions]

    action_items = []
    if isinstance(raw_actions, list):
        for item in raw_actions:
            if isinstance(item, dict):
                task = item.get("task") or item.get("title") or item.get("description") or item.get("action")
                assignee = item.get("assignee") or item.get("owner") or "Unassigned"
                due = item.get("due") or item.get("due_date") or item.get("deadline")
                priority = str(item.get("priority") or "medium").lower()
            else:
                task = item
                assignee = "Unassigned"
                due = None
                priority = "medium"

            task = str(task or "").strip()
            if not task:
                continue
            assignee = str(assignee or "Unassigned").strip() or "Unassigned"
            if due is not None:
                due = str(due).strip() or None
            if priority not in valid_priorities:
                priority = "medium"
            action_items.append(ActionItem(task=task, assignee=assignee, due=due, priority=priority))

    action_items = post_process_action_items(action_items, transcript)

    # Extract participants from transcript speaker labels
    participants = data.get("participants") or []
    if not participants and transcript:
        seen = set()
        for line in transcript.splitlines():
            speaker, _ = split_speaker_statement(line.strip())
            if speaker and speaker.lower() not in seen:
                seen.add(speaker.lower())
                participants.append(speaker)

    if not key_notes:
        key_notes = fallback.key_notes

    return AnalyzeMeetingResponse(
        summary=summary,
        key_notes=key_notes,
        action_items=action_items or fallback.action_items,
        participants=participants,
    )

